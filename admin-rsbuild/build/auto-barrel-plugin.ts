// plugins/auto-barrel-plugin.ts
import type { RspackPluginInstance, Compiler, Compilation } from '@rspack/core';
import {
  readdirSync,
  statSync,
  existsSync,
  writeFileSync,
  readFileSync,
} from 'fs';
import { join, relative, resolve, extname } from 'path';
import chokidar from 'chokidar';
import { camelCase, upperFirst } from 'lodash-es';

function toPascalCase(str: string) {
  return upperFirst(camelCase(str));
}

interface DirItem {
  path: string;
  named?: boolean;
  nameTransformer?: (exportName: string, importName: string) => string;
}

export interface AutoBarrelPluginOptions {
  /** 要扫描的目录路径（相对于项目根目录） */
  dir: DirItem[];
  /** 是否递归扫描子目录 */
  recursive?: boolean;
  /** 文件扩展名过滤 */
  extensions?: string[];
  /** 排除的文件/目录 */
  exclude?: RegExp[];
  /** 是否仅在开发模式运行 */
  devOnly?: boolean;
}

export class AutoBarrelPlugin implements RspackPluginInstance {
  private options: Required<AutoBarrelPluginOptions>;
  private watcher?: chokidar.FSWatcher;
  private isWatching = false;

  constructor(options: AutoBarrelPluginOptions) {
    this.options = {
      dir: options.dir,
      recursive: options.recursive ?? false,
      extensions: options.extensions ?? ['.ts', '.tsx', '.js', '.jsx'],
      exclude: options.exclude ?? [/\.d\.ts$/, /index\.(ts|js)$/],
      devOnly: options.devOnly ?? false,
    };
  }

  /** 扫描目录获取所有模块文件 */
  private scanDirectory(dirPath: string): Map<string, string> {
    const exports = new Map<string, string>();
    const absoluteDir = resolve(process.cwd(), dirPath);

    if (!existsSync(absoluteDir)) {
      console.warn(`[AutoBarrelPlugin] 目录不存在: ${absoluteDir}`);
      return exports;
    }

    const scan = (currentPath: string, relativeBase: string = '') => {
      const items = readdirSync(currentPath);

      for (const item of items) {
        // 跳过排除项
        if (this.options.exclude.some((pattern) => pattern.test(item))) {
          continue;
        }

        const fullPath = join(currentPath, item);
        const stat = statSync(fullPath);

        if (stat.isDirectory()) {
          // 递归扫描子目录
          if (this.options.recursive) {
            scan(fullPath, join(relativeBase, item));
          }
        } else if (stat.isFile()) {
          // 检查文件扩展名
          const ext = extname(item);
          if (this.options.extensions.includes(ext)) {
            const relativePath = join(relativeBase, item);
            // 生成相对导入路径
            const importPath = `./${relativePath.replace(/\\/g, '/').replace(ext, '')}`;
            exports.set(relativePath, importPath);
          }
        }
      }
    };

    scan(absoluteDir);
    return exports;
  }

  /** 生成 index.ts 内容 */
  private generateIndexContent(
    dir: DirItem,
    exports: Map<string, string>,
  ): string {
    const lines: string[] = [
      '// Auto-generated by AutoBarrelPlugin',
      '// DO NOT EDIT MANUALLY',
      '',
    ];

    // 按名称排序
    const sortedExports = Array.from(exports.entries()).sort((a, b) =>
      a[0].localeCompare(b[0]),
    );

    for (let [exportName, importPath] of sortedExports) {
      const temps = exportName.split('/');
      exportName = temps[temps.length - 1].replace(/\.(ts|tsx|js|jsx)$/, '');
      if (exportName === 'index') {
        exportName = temps[temps.length - 2];
      }
      exportName = toPascalCase(exportName);
      const newName = dir.nameTransformer
        ? dir.nameTransformer(exportName, importPath)
        : exportName;

      if (dir.named) {
        lines.push(`export { default as ${newName} } from '${importPath}';`);
      } else {
        lines.push(`export * as ${newName} from '${importPath}';`);
      }
    }

    // 添加命名导出支持（如果文件有命名导出）
    lines.push('');
    // lines.push('// Named exports');
    // for (const [exportName, importPath] of sortedExports) {
    //   lines.push(`export * from '${importPath}';`);
    // }

    return lines.join('\n');
  }

  /** 写入 index.ts 文件 */
  private writeIndexFile(
    dir: DirItem,
    exports: Map<string, string>,
    compilation?: Compilation,
  ): void {
    const content = this.generateIndexContent(dir, exports);
    const outputPath = resolve(process.cwd(), dir.path, 'index.ts');

    // 确保输出目录存在
    const outputDir = join(outputPath, '..');
    if (!existsSync(outputDir)) {
      // 目录不存在时跳过，由构建流程处理
      return;
    }

    // 检查内容是否变化，避免不必要的写入
    let shouldWrite = true;
    if (existsSync(outputPath)) {
      const existingContent = readFileSync(outputPath, 'utf-8');
      if (existingContent === content) {
        shouldWrite = false;
      }
    }

    if (shouldWrite) {
      writeFileSync(outputPath, content, 'utf-8');
      console.log(`[AutoBarrelPlugin] 已更新: ${outputPath}`);
    }

    // 如果有 compilation，也作为 asset  emit
    if (compilation) {
      const relativePath = relative(process.cwd(), outputPath);
      compilation.emitAsset(relativePath, {
        source: () => content,
        size: () => content.length,
      });
    }
  }

  /** 初始化文件监听（开发模式） */
  private setupWatcher(compiler: Compiler): void {
    if (this.watcher) {
      this.watcher.close();
    }

    const watchPath = this.options.dir.map((dir) =>
      resolve(process.cwd(), dir.path),
    );

    this.watcher = chokidar.watch(watchPath, {
      ignored: /node_modules|\.git|index\.(ts|js)/,
      persistent: true,
      ignoreInitial: true,
    });

    const regenerate = () => {
      this.options.dir.forEach((dir) => {
        const exports = this.scanDirectory(dir.path);
        this.writeIndexFile(dir, exports);
      });
    };

    this.watcher
      .on('add', regenerate)
      .on('unlink', regenerate)
      .on('change', regenerate)
      .on('addDir', regenerate)
      .on('unlinkDir', regenerate);

    console.log(`[AutoBarrelPlugin] 监听目录: ${watchPath}`);
  }

  apply(compiler: Compiler): void {
    const { devOnly } = this.options;

    // 生产模式且 devOnly=true 时跳过
    if (devOnly && compiler.options.mode === 'production') {
      return;
    }

    // 在编译开始前生成 index.ts
    compiler.hooks.beforeCompile.tapPromise('AutoBarrelPlugin', async () => {
      this.options.dir.forEach((dir) => {
        const exports = this.scanDirectory(dir.path);
        this.writeIndexFile(dir, exports);
      });
    });

    // 开发模式下设置文件监听
    if (compiler.options.mode === 'development' || compiler.options.watch) {
      this.isWatching = true;
      compiler.hooks.watchRun.tap('AutoBarrelPlugin', () => {
        if (!this.watcher) {
          this.setupWatcher(compiler);
        }
      });
    }

    // 清理监听器
    compiler.hooks.shutdown.tap('AutoBarrelPlugin', () => {
      if (this.watcher) {
        this.watcher.close();
      }
    });
  }
}
